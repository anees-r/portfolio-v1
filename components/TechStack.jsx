function placeTech(items, radiusFactor) {
  return items.map((item, i) => {
    const angle = (i / items.length) * Math.PI * 2 - Math.PI / 2;
    const x = 50 + radiusFactor * Math.cos(angle) * 100;
    const y = 50 + radiusFactor * Math.sin(angle) * 100;
    return { ...item, x, y };
  });
}

